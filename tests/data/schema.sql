    collision_type_code TEXT,
    collision_type_description TEXT,
    collision_type_other_description TEXT,
    day_of_week TEXT,
    dispatch_notified TEXT,
    has_photographs INTEGER,
    hit_run TEXT,
    is_attachments_mailed INTEGER,
    is_deleted INTEGER,
    is_highway_related INTEGER,
    is_tow_away INTEGER,
    judicial_district TEXT,
    motor_vehicle_involved_with_code TEXT,
    motor_vehicle_involved_with_description TEXT,
    motor_vehicle_involved_with_other_description TEXT,
    number_injured INTEGER,
    number_killed INTEGER,
    weather_1 TEXT,
    weather_2 TEXT,
    road_condition_1 TEXT,
    road_condition_2 TEXT,
    special_condition TEXT,
    lighting_code TEXT,
    lighting_description TEXT,
    latitude REAL,
    longitude REAL,
    milepost_direction TEXT,
    milepost_distance REAL,
    milepost_marker TEXT,
    milepost_unit_of_measure TEXT,
    pedestrian_action_code TEXT,
    pedestrian_action_description TEXT,
