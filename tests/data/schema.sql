CREATE TABLE parties (
    party_id INTEGER PRIMARY KEY,
    collision_id INTEGER REFERENCES crashes(collision_id),
    party_number INTEGER,
    party_type TEXT,
    is_at_fault INTEGER,
    is_on_duty_emergency_vehicle INTEGER,
    is_hit_and_run INTEGER,
    airbag_code TEXT,
    airbag_description TEXT,
    safety_equipment_code TEXT,
    safety_equipment_description TEXT,
    special_information TEXT,
    other_associate_factor TEXT,
    inattention TEXT,
    direction_of_travel TEXT,
    street_or_highway_name TEXT,
    speed_limit INTEGER,
    movement_preceding_collision_code TEXT,
    movement_preceding_collision_description TEXT,
    sobriety_drug_physical_code_1 TEXT,
    sobriety_drug_physical_description_1 TEXT,
    sobriety_drug_physical_code_2 TEXT,
    sobriety_drug_physical_description_2 TEXT,
    gender_code TEXT,
    gender_description TEXT,
    stated_age INTEGER,
    driver_license_class TEXT,
    driver_license_state_code TEXT,
    race_code TEXT,
    race_description TEXT,
    lane TEXT,
    thru_lanes INTEGER,
    total_lanes INTEGER,
    is_dre_conducted INTEGER
) STRICT;

CREATE TABLE vehicles (
    party_id INTEGER REFERENCES parties(party_id),
    collision_id INTEGER REFERENCES crashes(collision_id),
    vehicle_number INTEGER,
    type_id INTEGER,
    type_description TEXT,
    year INTEGER,
    make_raw TEXT,
    make TEXT,
    model TEXT,
    color_raw TEXT,
    color TEXT,
    color_secondary TEXT,
    is_towed INTEGER,
    PRIMARY KEY (party_id, vehicle_number)
) STRICT;

CREATE TABLE injured_witness_passengers (
    injured_witness_passenger_id INTEGER PRIMARY KEY,
    collision_id INTEGER REFERENCES crashes(collision_id),
    party_number INTEGER,
    stated_age INTEGER,
    gender_code TEXT,
    gender_description TEXT,
    race_code TEXT,
    race_description TEXT,
    is_witness_only INTEGER,
    is_passenger_only INTEGER,
    extent_of_injury_code TEXT,
    injured_person_type TEXT,
    seat_position TEXT,
    seat_position_other TEXT,
    seat_position_description TEXT,
    airbag_code TEXT,
    airbag_description TEXT,
    safety_equipment_code TEXT,
    safety_equipment_description TEXT,
    ejected TEXT,
    is_vovc_notified INTEGER
) STRICT;

CREATE TABLE metadata (
    record_type TEXT NOT NULL,
    table_name TEXT NOT NULL,
    source_file TEXT,
    year_label TEXT,
    rows_read INTEGER,
    rows_loaded INTEGER,
    rows_skipped INTEGER,
    orphan_rows INTEGER,
    converter_version TEXT NOT NULL,
    loaded_at_utc TEXT NOT NULL,
    CHECK (record_type IN ('file_load', 'orphan_count'))
) STRICT;

CREATE INDEX index_crashes_crash_date ON crashes (crash_date);

CREATE INDEX index_parties_collision_id_party_number ON parties (collision_id, party_number);

CREATE INDEX index_vehicles_collision_id ON vehicles (collision_id);

CREATE INDEX index_injured_witness_passengers_collision_id_party_number ON injured_witness_passengers (collision_id, party_number);
