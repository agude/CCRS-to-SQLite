    primary_collision_factor_code TEXT,
    primary_collision_factor_violation TEXT,
    primary_collision_factor_is_cited INTEGER,
    primary_collision_party_number INTEGER,
    primary_road TEXT,
    reporting_district TEXT,
    reporting_district_code TEXT,
    reviewed_date TEXT,
    roadway_surface_code TEXT,
    secondary_direction TEXT,
    secondary_distance REAL,
    secondary_road TEXT,
    secondary_unit_of_measure TEXT,
    sketch_description TEXT,
    traffic_control_device_code TEXT,
    created_date TEXT,
    modified_date TEXT,
    is_county_road INTEGER,
    is_freeway INTEGER,
    chp_555_version INTEGER,
    is_additional_object_struck INTEGER,
    notification_date TEXT,
    notification_time TEXT,
    notification_time_description TEXT,
    notification_time_merged TEXT,
    has_digital_media_files INTEGER,
